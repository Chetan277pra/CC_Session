#include <bits/stdc++.h>
using namespace std;
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    int tt;
    if(!(cin >> tt)) return 0;
    while (tt--) {
        int n;
        cin >> n;
        vector<int> a(n);
        for (int i = 0; i < n; ++i) cin >> a[i];
        int mn = INT_MAX;
        int mn2 = INT_MAX;
        int ans = 0;
        for (int i = 0; i < n; ++i) {
            int x = a[i];
            if (mn < x && x < mn2) {
                ++ans;
                mn2 = x;
            }
            if (x < mn) mn = x;
        }
        cout << ans << '\n';
    }
    return 0;
}
